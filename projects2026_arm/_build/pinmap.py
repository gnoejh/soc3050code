"""Draw each lesson's pins - on the board and in the chip - into its Slide.md.

Students otherwise meet "PA6" and "PB8" as names and have to imagine where
they are.  This draws two pictures per lesson, derived rather than drawn:

  BOARD VIEW  the Nucleo-C031C6's headers to scale, as Wokwi lays them out,
              with the exact header pins the lesson's diagram.json wires to
              highlighted and labelled.  Positions come from Wokwi's board
              definition; which pins, from the lesson's own diagram.json - so
              the picture cannot disagree with the circuit students paste.

  CHIP VIEW   ports A and B as sixteen bit-cells each, pin 15 on the left and
              pin 0 on the right (the order registers are drawn in), with the
              lesson's pins marked by what they are configured as.  That part
              is course knowledge, in the LESSONS table below.

Usage (from projects2026_arm/):
    python _build/pinmap.py              # regenerate every lesson's pictures
    python _build/pinmap.py --refresh    # re-derive the layout facts from Wokwi
    python _build/pinmap.py --refresh board.json   # ... from a local copy

The layout facts are _targets/c031c6-layout.json: pin name -> (x, y) in mm.
Like c031c6-pins.json, they are facts derived from Wokwi's board file, which
declares no licence, so the file itself is not vendored.

Where the pictures go: a Slide.md opts in by containing a ```svg block whose
first line is the marker comment below.  Only those blocks are rewritten; a
comment inside SVG is invisible when rendered.
"""
