# ---------------------------------------------------------------------------
# --refresh: Wokwi's board file -> the layout facts
# ---------------------------------------------------------------------------
def refresh(path):
    if path:
        raw = open(path, encoding="utf-8").read()
    else:
        import urllib.request
        raw = urllib.request.urlopen(SOURCE, timeout=30).read().decode("utf-8")
    raw = re.sub(r"//[^\n]*", "", raw)                 # JSON5-ish: // comments
    raw = re.sub(r",(\s*[}\]])", r"\1", raw)            # ... and trailing commas
    board = json.loads(raw)
    facts = {
        "board": board["name"],
        "source": SOURCE,
        "derived": datetime.date.today().isoformat(),
        "note": "Header pin positions in mm, derived from Wokwi's board definition. "
                "Regenerate with python _build/pinmap.py --refresh",
        "width_mm": board["width"],
        "height_mm": board["height"],
        "pins": {k: [round(v["x"], 2), round(v["y"], 2)] for k, v in board["pins"].items()},
    }
    with open(LAYOUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(facts, f, indent=1, sort_keys=False)
        f.write("\n")
    print(f"wrote {os.path.relpath(LAYOUT, BASE)}: {len(facts['pins'])} pins")


